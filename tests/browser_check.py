"""Local prototype integration check. Uses only the local static server."""
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

root=Path(__file__).resolve().parents[1]
out=root/'test-artifacts';out.mkdir(exist_ok=True)
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1050})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    responses=[];page.on('response',lambda r:responses.append((r.url,r.status)))
    page.route('**/api/status',lambda route:route.fulfill(json={'enabled':False}))
    page.route('**/api/prices',lambda route:route.fulfill(json={'version':1,'records':[],'sources':{}}))
    page.goto('http://127.0.0.1:8787/',wait_until='domcontentloaded')
    page.locator('#quiz-skip').click()
    expect(page.locator('.recipe-card')).to_have_count(3)
    expect(page.locator('#menu-count')).to_have_text('21')
    expect(page.locator('.demo-banner')).to_contain_text('Verifierade')
    expect(page.locator('#store-options input')).to_have_count(6)
    page.get_by_role('button',name='Välj alla',exact=True).click()
    expect(page.locator('#store-count')).to_have_text('6 av 6 valda')
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('.store-card')).to_have_count(6)
    expect(page.locator('.store-card').filter(has_text='Matsmart')).to_contain_text('Pris saknas')
    page.get_by_role('button',name='Rensa',exact=True).click()
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('#form-error')).to_contain_text('Välj minst en butik')
    for store in ('willys','coop','ica'):page.locator(f'label:has(input[name="stores"][value="{store}"])').click()
    page.get_by_role('button',name='Skapa min matplan').click()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path=str(out/'desktop.png'),full_page=True)
    first=page.locator('.recipe-card h4').first.inner_text()
    page.get_by_role('button',name='Se recept →').first.click()
    expect(page.locator('#recipe-dialog')).to_be_visible()
    expect(page.locator('#recipe-detail h2')).to_have_text(first)
    assert page.locator('.ingredient-list li').count()>2
    assert page.locator('.cooking-steps li').count()>1
    page.get_by_role('button',name='Stäng recept',exact=True).click()
    page.get_by_role('button',name='↻ Byt recept').first.click()
    expect(page.locator('#replace-dialog')).to_be_visible()
    page.locator('#replacement-list button').first.click()
    assert page.locator('.recipe-card h4').first.inner_text()!=first
    for meal in ('breakfast','lunch'):
        page.locator(f'label:has(input[name="meals"][value="{meal}"])').click()
        expect(page.locator(f'input[name="meals"][value="{meal}"]')).not_to_be_checked()
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('.recipe-card')).to_have_count(1)
    expect(page.locator('#menu-count')).to_have_text('7')
    page.get_by_label('Matpreferens',exact=True).select_option('vegan')
    page.get_by_label('Max tid',exact=True).select_option('15')
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('.recipe-card h4')).to_have_text('Bönwraps med varm tomatröra')
    page.locator('label:has(input[name="period"][value="month"])').click()
    page.locator('#month').fill('2027-01')
    page.get_by_label('Max tid',exact=True).select_option('30')
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('#menu-count')).to_have_text('31')
    for _ in range(4):page.get_by_role('button',name='Nästa sju dagar').click()
    expect(page.locator('#day-tabs button')).to_have_count(3)
    page.locator('#budget').fill('1')
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('#stat-cost')).to_have_text('Saknar priser')
    expect(page.locator('#budget-message')).to_contain_text('kan därför inte beräknas')
    expect(page.locator('#menu-count')).to_have_text('31')
    page.get_by_label('Jag kan handla i',exact=True).select_option('2')
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('#split-summary')).to_be_hidden()
    page.locator('#shopping-tab').click()
    page.locator('.shopping-row input').first.check()
    expect(page.locator('.shopping-row.done')).to_have_count(1)
    page.reload(wait_until='domcontentloaded')
    page.locator('#shopping-tab').click()
    expect(page.locator('.shopping-row.done')).to_have_count(1)
    page.locator('label:has(input[name="meals"][value="dinner"])').click()
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('#form-error')).to_contain_text('Välj minst en måltid')
    page.evaluate('localStorage.clear()');page.reload(wait_until='domcontentloaded')
    page.locator('#quiz-skip').click()
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path=str(out/'mobile.png'),full_page=True)
    page.get_by_role('button',name='Välj alla',exact=True).click()
    page.get_by_role('button',name='Skapa min matplan').click()
    expect(page.locator('.store-card')).to_have_count(6)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    assert not errors,errors
    assert all(status<400 for _,status in responses),responses
    assert all(url.startswith('http://127.0.0.1:8787/') for url,_ in responses),responses
    browser.close()
print('PASS: recipes, replacements, meal exclusions, vegan/time filters, 31-day month, missing-price safety, unknown split basket, saved checklist, empty-meal validation and mobile width; no external network requests.')
