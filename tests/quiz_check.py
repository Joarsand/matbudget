from pathlib import Path
from playwright.sync_api import sync_playwright,expect

out=Path(__file__).resolve().parents[1]/'test-artifacts';out.mkdir(exist_ok=True)
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1360,'height':1000})
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:8787/',wait_until='domcontentloaded')
    quiz=page.locator('#preference-quiz')
    expect(quiz).to_be_visible()
    page.screenshot(path=str(out/'quiz-desktop.png'))
    page.locator('#quiz-budget').fill('750');page.locator('#quiz-people').select_option('1')
    page.locator('#quiz-next').click()
    expect(page.locator('#quiz-step-label')).to_have_text('Steg 2 av 5')
    for m in ('breakfast','lunch','dinner'):quiz.locator(f'label:has(input[name="quiz-meals"][value="{m}"])').click()
    page.locator('#quiz-next').click()
    expect(page.locator('#quiz-error')).to_contain_text('Välj minst en måltid')
    quiz.locator('label:has(input[name="quiz-meals"][value="dinner"])').click()
    page.locator('#quiz-next').click()
    quiz.locator('label:has(input[name="quiz-diet"][value="vegan"])').click()
    page.locator('#quiz-time').select_option('20')
    page.locator('#quiz-back').click()
    expect(quiz.locator('input[name="quiz-meals"][value="dinner"]')).to_be_checked()
    page.locator('#quiz-next').click()
    expect(page.locator('#quiz-time')).to_have_value('20')
    expect(quiz.locator('input[name="quiz-diet"][value="vegan"]')).to_be_checked()
    page.locator('#quiz-next').click()
    quiz.locator('label:has(input[name="quiz-exclusions"][value="milk"])').click()
    quiz.locator('label:has(input[name="quiz-avoid"][value="onion"])').click()
    page.locator('#quiz-next').click()
    for s in ('willys','coop','ica'):quiz.locator(f'label:has(input[name="quiz-stores"][value="{s}"])').click()
    page.locator('#quiz-next').click()
    expect(page.locator('#quiz-error')).to_contain_text('Välj minst en butik')
    quiz.locator('label:has(input[name="quiz-stores"][value="lidl"])').click()
    page.locator('#quiz-next').click()
    expect(quiz).to_be_hidden()
    expect(page.locator('#people')).to_have_value('1');expect(page.locator('#budget')).to_have_value('750')
    expect(page.locator('#diet')).to_have_value('vegan');expect(page.locator('#max-time')).to_have_value('20')
    expect(page.locator('#menu-count')).to_have_text('7');expect(page.locator('.recipe-card')).to_have_count(1)
    expect(page.locator('input[name="avoidIngredients"][value="onion"]')).to_be_checked()
    expect(page.locator('.recipe-card h4')).to_have_text('Gyllene kikärtsgryta')
    expect(page.locator('.store-card')).to_have_count(1)
    page.reload(wait_until='domcontentloaded');expect(quiz).to_be_hidden()
    expect(page.locator('#budget')).to_have_value('750')
    expect(page.locator('input[name="avoidIngredients"][value="onion"]')).to_be_checked()
    # Reopen and cancel: uncommitted answers must not overwrite the saved plan.
    page.locator('#open-quiz').click();page.locator('#quiz-budget').fill('999');page.locator('#quiz-skip').click()
    expect(page.locator('#budget')).to_have_value('750')
    # An incompatible preference combination remains in the quiz without losing the plan.
    page.locator('#open-quiz').click();page.locator('#quiz-next').click();page.locator('#quiz-next').click()
    page.locator('#quiz-time').select_option('15');page.locator('#quiz-next').click()
    quiz.locator('label:has(input[name="quiz-exclusions"][value="gluten"])').click()
    page.locator('#quiz-next').click();page.locator('#quiz-next').click()
    expect(quiz).to_be_visible();expect(page.locator('#quiz-error')).to_contain_text('matchar alla val')
    expect(page.locator('#max-time')).to_have_value('20');expect(page.locator('#menu-count')).to_have_text('7')
    page.locator('#quiz-skip').click()
    # Calendar month selection and mobile layout.
    page.locator('#open-quiz').click()
    quiz.locator('label:has(input[name="quiz-period"][value="month"])').click()
    page.locator('#quiz-date').fill('2027-02')
    for _ in range(5):page.locator('#quiz-next').click()
    expect(quiz).to_be_hidden();expect(page.locator('#menu-count')).to_have_text('28')
    page.set_viewport_size({'width':390,'height':844});page.locator('#open-quiz').click()
    expect(page.locator('#quiz-budget')).to_have_value('750')
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    assert quiz.evaluate('e=>e.scrollWidth<=e.clientWidth')
    page.screenshot(path=str(out/'quiz-mobile.png'))
    page.locator('#quiz-skip').click()
    assert not errors,errors
    browser.close()
print('PASS: first-visit quiz; back/next retention; meal/store validation; all answers applied to actual plan; disliked ingredient excluded; saved preferences; skip preserves plan; no-match recovery; actual month; mobile.')
